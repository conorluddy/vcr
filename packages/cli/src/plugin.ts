import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { basename, extname, join, relative } from "node:path";
import { renderCliReference } from "./commands.js";
import { fail, ok, type Result } from "./result.types.js";
import type { Diagnostic } from "./validate.js";

// === TYPES ===

export interface PluginBuildOutcome {
  directory: string;
  version: string;
  fileCount: number;
  totalBytes: number;
  /** Bytes each pillar's references add, so their share of the size cap stays visible. */
  pillarBytes: Record<string, number>;
}

export const PLUGIN_DIRECTORY = "plugin";
export const PLUGIN_MAX_BYTES = 5 * 1024 * 1024;
export const CLI_REFERENCE_PATH = "references/cli.md";
/** `references/` entries that are not pillars and stay out of the plugin: research briefs and exploratory notes. */
const NON_PILLAR_REFERENCES = new Set(["research-prompts", "ideas"]);

/** One source for both host manifests (PRD §6.7). */
const PLUGIN_IDENTITY = {
  name: "vcr",
  description: "Agent studio for code-first motion graphics and video: tool catalogue, operating guides, deterministic browser capture and a human review loop.",
  author: { name: "Conor Luddy", url: "https://github.com/conorluddy" },
  repository: "https://github.com/conorluddy/vcr",
  keywords: ["video", "motion-graphics", "gsap", "three-js", "p5", "ffmpeg", "capture"],
};

const PLUGIN_README = `# VCR plugin

Generated by \`vcr plugin build\` from the harness repository. Do not edit; edit the sources and rebuild.

Install: \`claude plugin install vcr@vcr\` or \`codex plugin add vcr@vcr\` after adding the repository's marketplace. Then ask the agent to set up VCR (\`/vcr:init\` in Claude Code).

The CLI is \`node <this directory>/cli/vcr.mjs\` (Node 22 or newer). It never writes here: projects live in the workspace (\`vcr.json\`), machine state in \`VCR_HOME\` (default \`~/.vcr\`).
`;

const LICENSE_FILES = ["LICENSE", "NOTICE", "THIRD_PARTY_NOTICES"];
const CATALOG_ENTRIES = ["INDEX.md", "CANDIDATES.md", "tools.json", "tools", "schemas", "capabilities", "CANDIDATE-INGESTION.md", "ASSESSMENT-BRIEF.md", "FIXTURE-EVIDENCE-TEMPLATE.md"];
const SKIPPED_DIRECTORIES = new Set(["node_modules", "output", ".cache", "dist"]);
const MEDIA_EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".gif", ".webp", ".mp4", ".mov", ".webm", ".wav", ".mp3", ".aac", ".glb", ".gltf", ".blend", ".exr", ".woff", ".woff2"]);

// === PUBLIC API ===

/** Assembles `plugin/` from the harness: bundled CLI, catalogue, skills, agents, pillar references, example sources and both manifests. Maintainer only. */
export function buildPlugin(harnessRoot: string, outputDirectory = join(harnessRoot, PLUGIN_DIRECTORY)): Result<PluginBuildOutcome> {
  const version = readHarnessVersion(harnessRoot);
  if (!version.ok) return version;
  for (const file of LICENSE_FILES) {
    if (!existsSync(join(harnessRoot, file))) return fail("PLUGIN_LICENSE_MISSING", `Required distribution file ${file} is missing from ${harnessRoot}.`);
  }
  rmSync(outputDirectory, { recursive: true, force: true });
  mkdirSync(outputDirectory, { recursive: true });

  const bundled = bundleCli(harnessRoot, join(outputDirectory, "cli/vcr.mjs"));
  if (!bundled.ok) return bundled;
  for (const file of LICENSE_FILES) cpSync(join(harnessRoot, file), join(outputDirectory, file));
  for (const entry of CATALOG_ENTRIES) cpSync(join(harnessRoot, "catalog", entry), join(outputDirectory, "catalog", entry), { recursive: true });
  for (const skill of readdirSync(join(harnessRoot, "skills"))) {
    if (existsSync(join(harnessRoot, "skills", skill, "SKILL.md"))) cpSync(join(harnessRoot, "skills", skill), join(outputDirectory, "skills", skill), { recursive: true });
  }
  cpSync(join(harnessRoot, "agents"), join(outputDirectory, "agents"), { recursive: true });
  const examplesRoot = join(harnessRoot, "examples");
  cpSync(examplesRoot, join(outputDirectory, "examples"), { recursive: true, filter: (source) => !SKIPPED_DIRECTORIES.has(basename(source)) && !isRepoOnlyExample(examplesRoot, source) });
  writeManifests(outputDirectory, version.value);
  writeFileSync(join(outputDirectory, "README.md"), PLUGIN_README);
  const cliReference = renderCliReference();
  mkdirSync(join(outputDirectory, "references"), { recursive: true });
  writeFileSync(join(outputDirectory, CLI_REFERENCE_PATH), cliReference);
  for (const pillar of listPillarReferences(harnessRoot)) cpSync(join(harnessRoot, "references", pillar), join(outputDirectory, "references", pillar), { recursive: true });
  for (const file of ["README.md", "INDEX.md"]) if (existsSync(join(harnessRoot, "references", file))) cpSync(join(harnessRoot, "references", file), join(outputDirectory, "references", file));
  if (outputDirectory === join(harnessRoot, PLUGIN_DIRECTORY)) writeFileSync(join(harnessRoot, CLI_REFERENCE_PATH), cliReference);

  const files = listFiles(outputDirectory);
  const totalBytes = files.reduce((sum, file) => sum + statSync(join(outputDirectory, file)).size, 0);
  const pillarBytes = Object.fromEntries(listPillarReferences(harnessRoot).map((pillar) => [pillar, files.filter((file) => file.startsWith(`references/${pillar}/`)).reduce((sum, file) => sum + statSync(join(outputDirectory, file)).size, 0)]));
  return ok({ directory: outputDirectory, version: version.value, fileCount: files.length, totalBytes, pillarBytes });
}

/** `plugin/` must equal a fresh build, stay under the size cap and carry no media. */
export function pluginDiagnostics(harnessRoot: string): Diagnostic[] {
  const committed = join(harnessRoot, PLUGIN_DIRECTORY);
  const file = PLUGIN_DIRECTORY;
  if (!existsSync(committed)) return [{ severity: "error", file, path: "", message: "plugin/ is missing", suggestion: "Run `pnpm vcr plugin build` and commit the result." }];
  const fresh = buildPlugin(harnessRoot, mkdtempSync(join(tmpdir(), "vcr-plugin-")));
  if (!fresh.ok) return [{ severity: "error", file, path: "", message: fresh.error.message }];

  const diagnostics: Diagnostic[] = [];
  const harnessReference = join(harnessRoot, CLI_REFERENCE_PATH);
  if (!existsSync(harnessReference) || readFileSync(harnessReference, "utf8") !== renderCliReference()) {
    diagnostics.push({ severity: "error", file: CLI_REFERENCE_PATH, path: "", message: `${CLI_REFERENCE_PATH} is missing or stale against packages/cli/src/commands.ts`, suggestion: "Run `pnpm vcr plugin build` and commit the result." });
  }
  const staleFiles = differingFiles(committed, fresh.value.directory);
  if (staleFiles.length > 0) diagnostics.push({ severity: "error", file, path: "", message: `plugin/ is stale: ${staleFiles.slice(0, 5).join(", ")}${staleFiles.length > 5 ? ` and ${staleFiles.length - 5} more` : ""}`, suggestion: "Run `pnpm vcr plugin build` and commit the result." });
  if (fresh.value.totalBytes > PLUGIN_MAX_BYTES) diagnostics.push({ severity: "error", file, path: "", message: `plugin/ is ${(fresh.value.totalBytes / 1024 / 1024).toFixed(1)} MB; the cap is 5 MB` });
  const mediaFiles = listFiles(fresh.value.directory).filter((path) => MEDIA_EXTENSIONS.has(extname(path).toLowerCase()));
  if (mediaFiles.length > 0) diagnostics.push({ severity: "error", file, path: "", message: `plugin/ would ship media: ${mediaFiles.join(", ")}`, suggestion: "Keep media out of examples/ sources or under an ignored output/ directory." });
  rmSync(fresh.value.directory, { recursive: true, force: true });
  return diagnostics;
}

/** The plugin manifest when running from an installed plugin; the CLI package in the harness repository. */
export function readHarnessVersion(harnessRoot: string): Result<string> {
  for (const candidate of [".claude-plugin/plugin.json", "packages/cli/package.json"]) {
    const path = join(harnessRoot, candidate);
    if (existsSync(path)) return ok((JSON.parse(readFileSync(path, "utf8")) as { version: string }).version);
  }
  return fail("HARNESS_VERSION_UNKNOWN", `Neither .claude-plugin/plugin.json nor packages/cli/package.json exists under ${harnessRoot}.`);
}

/** Pillar reference directories: every `references/<pillar>/` with a README, except research briefs and exploratory notes. */
export function listPillarReferences(harnessRoot: string): string[] {
  const referencesDirectory = join(harnessRoot, "references");
  if (!existsSync(referencesDirectory)) return [];
  return readdirSync(referencesDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !NON_PILLAR_REFERENCES.has(entry.name) && existsSync(join(referencesDirectory, entry.name, "README.md")))
    .map((entry) => entry.name)
    .sort();
}

// === PRIVATE HELPERS ===

/** A top-level example with a `scene.tsx` needs the repo's esbuild step, which `vcr capture` lacks (#196), so the plugin does not ship it. */
function isRepoOnlyExample(examplesRoot: string, source: string): boolean {
  return relative(examplesRoot, source).split(/[\\/]/).length === 1 && existsSync(join(source, "scene.tsx"));
}

function bundleCli(harnessRoot: string, outfile: string): Result<string> {
  // esbuild is a maintainer-only dev dependency: required lazily so the bundle never needs it.
  const esbuild = createRequire(import.meta.url)("esbuild") as typeof import("esbuild");
  const result = esbuild.buildSync({
    entryPoints: [join(harnessRoot, "packages/cli/src/index.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    external: ["esbuild", "playwright"],
    // CommonJS dependencies (ajv) call require(); give the ESM bundle one.
    banner: { js: 'import { createRequire as __vcrCreateRequire } from "node:module"; const require = __vcrCreateRequire(import.meta.url);' },
    legalComments: "inline",
    logLevel: "silent",
    write: false,
  });
  const output = result.outputFiles[0];
  if (!output) return fail("PLUGIN_BUNDLE_FAILED", "esbuild produced no output for packages/cli/src/index.ts");
  mkdirSync(join(outfile, ".."), { recursive: true });
  writeFileSync(outfile, output.text);
  return ok(outfile);
}

function writeManifests(outputDirectory: string, version: string): void {
  const claudeManifest = { ...PLUGIN_IDENTITY, version };
  const codexManifest = {
    ...PLUGIN_IDENTITY,
    version,
    skills: "./skills/",
    interface: { displayName: "VCR", shortDescription: "Code-first motion graphics and video", developerName: PLUGIN_IDENTITY.author.name, category: "Developer Tools" },
  };
  for (const [directory, manifest] of [[".claude-plugin", claudeManifest], [".codex-plugin", codexManifest]] as const) {
    mkdirSync(join(outputDirectory, directory), { recursive: true });
    writeFileSync(join(outputDirectory, directory, "plugin.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  }
}

function listFiles(root: string): string[] {
  const found: string[] = [];
  const walk = (directory: string): void => {
    for (const entry of readdirSync(directory)) {
      const path = join(directory, entry);
      if (statSync(path).isDirectory()) walk(path);
      else found.push(relative(root, path));
    }
  };
  walk(root);
  return found.sort();
}

function differingFiles(committedRoot: string, freshRoot: string): string[] {
  const committed = listFiles(committedRoot);
  const fresh = listFiles(freshRoot);
  const all = [...new Set([...committed, ...fresh])].sort();
  return all.filter((path) => {
    const committedPath = join(committedRoot, path);
    const freshPath = join(freshRoot, path);
    if (!existsSync(committedPath) || !existsSync(freshPath)) return true;
    return !readFileSync(committedPath).equals(readFileSync(freshPath));
  });
}
