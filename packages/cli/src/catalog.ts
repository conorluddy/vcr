import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { listJsonFiles, readJsonFile } from "./repository.js";
import { fail, ok, type Result } from "./result.types.js";
import type { ToolSummary } from "./tools.js";

// === TYPES ===

export interface CatalogIndex {
  schema_version: string;
  generated_from: "catalog/tools/*.json";
  resources: ToolSummary[];
}

export interface BuildOutcome {
  recordCount: number;
  /** True when a committed index file differs from what the per-tool files produce. */
  wasStale: boolean;
  staleFiles: string[];
}

/** Tier 0 lists the tools an agent may route to; candidates are listed separately in CANDIDATES.md. */
const ROUTABLE_TIERS = ["core", "catalogued"] as const;

const INDEX_HEADER = `# VCR tool index

Tier 0 of the catalogue tree, generated by \`vcr catalog build\`. One line per tool: id, one-line role, capabilities, validation evidence (✓ validated, ◐ partial) and whether a guide exists. Read this whole file (under 16 KB) to route a task, then descend only as far as the task needs:

- **Tier 1, the card** (about 300 tokens, at most about 600): \`vcr tools info <id>\` or \`catalog/tools/<id>.json\`. Summary, use when, avoid when, pairs with, install, evidence. Compare a shortlist here.
- **Tier 2, the guide** (1 to 2k tokens): \`vcr tools info <id> --full\` or \`skills/<id>/SKILL.md\`. Clock rules, recipes, gotchas. Load one at a time, once a tool is chosen.
- **Tier 3, examples** (source code): \`vcr tools examples <id>\` then \`examples/<id>/\`. Load one at a time.

Tiers: core = operational target with a skill and example; catalogued = real option with a known automation route. Candidates (seen during discovery, not yet assessed) are listed separately in \`CANDIDATES.md\`. ✓ = a validated evidence record exists, possibly on another OS or version and possibly for one use only (read the card's \`Evidence scope\`); ◐ = partial evidence. Neither means installed here: the card's \`Readiness\` line says that.

## Common chains

- Browser motion (DOM, SVG, canvas, WebGL): \`gsap\`, \`p5-js\` or \`three-js\` scene → \`vcr capture <scene.html> --width W --height H --fps F --verify\` (\`playwright\`; first run \`vcr setup capture --yes\`) → \`ffmpeg-ffprobe\`. For alpha, keep the page or clear colour transparent and deliver ProRes 4444 or VP9 yuva420p.
- GIF: frames → \`gifski\` (quality; AGPL; not validated) or \`ffmpeg-ffprobe\` palettegen (not covered by its evidence).
- Native 3D: \`blender\` frames → \`ffmpeg-ffprobe\`. Static vector: \`svg\` → \`resvg\` → PNG.
- Audio: mux and mix with \`ffmpeg-ffprobe\`; synthesise with \`web-audio\` or \`tone-js\`. No assessed tool does beat or onset detection; see \`aubio\`, \`meyda\` and \`essentia\` in \`CANDIDATES.md\`.
`;

/** The README keeps its own prose; only the text between these markers is generated. */
export const README_TOC_MARKERS = { start: "<!-- vcr:catalog-toc:start -->", end: "<!-- vcr:catalog-toc:end -->" } as const;

const CANDIDATES_HEADER = `# VCR candidate tools

Generated by \`vcr catalog build\`. Candidates were surfaced during discovery and have not been assessed: their records may be thin, and nothing here is validated or recommended. Route production work through \`INDEX.md\` instead. Use this list for gap research or to pick a tool to assess; promotion follows \`CANDIDATE-INGESTION.md\`. Cards and guides work the same way: \`vcr tools info <id>\`.
`;

// === PUBLIC API ===

export function buildCatalogIndex(repositoryRoot: string): Result<CatalogIndex> {
  const resources: ToolSummary[] = [];
  for (const filePath of listJsonFiles(join(repositoryRoot, "catalog/tools"))) {
    const record = readJsonFile<ToolSummary>(filePath);
    if (!record.ok) return record;
    const expectedFile = `${record.value.id}.json`;
    if (!filePath.endsWith(`/${expectedFile}`)) return fail("CATALOG_FILENAME_MISMATCH", `${filePath}: file must be named ${expectedFile} to match its id`);
    resources.push(record.value);
  }
  resources.sort((left, right) => left.id.localeCompare(right.id));
  return ok({ schema_version: "1.1.0", generated_from: "catalog/tools/*.json", resources });
}

export function serializeIndex(index: CatalogIndex): string {
  return `${JSON.stringify(index, null, 2)}\n`;
}

/** Tier 0 as Markdown: routable tools grouped by tier, one line per tool, sized to be read whole. */
export function renderMarkdownIndex(index: CatalogIndex, repositoryRoot: string): string {
  const sections = ROUTABLE_TIERS.map((tier) => {
    const tools = index.resources.filter((tool) => tool.tier === tier);
    const lines = tools.map((tool) => indexLine(tool, repositoryRoot));
    return `## ${tier} (${tools.length})\n\n${lines.join("\n")}\n`;
  });
  const candidates = index.resources.filter((tool) => tool.tier === "candidate").length;
  const pointer = `## candidate (${candidates})\n\nSeen during discovery, not assessed; do not route production work to them. List: \`CANDIDATES.md\` or \`vcr tools list --tier candidate\`.\n`;
  return `${INDEX_HEADER}\n${sections.join("\n")}\n${pointer}`;
}

/** Candidates as Markdown: one line per tool, kept out of tier 0 so routing stays cheap. */
export function renderCandidatesIndex(index: CatalogIndex, repositoryRoot: string): string {
  const tools = index.resources.filter((tool) => tool.tier === "candidate");
  const lines = tools.map((tool) => indexLine(tool, repositoryRoot));
  return `${CANDIDATES_HEADER}\n## candidate (${tools.length})\n\n${lines.join("\n")}\n`;
}

/** A human table of contents for the README: core tools in full, catalogued tools as links grouped by category. */
export function renderReadmeToc(index: CatalogIndex): string {
  const core = index.resources.filter((tool) => tool.tier === "core");
  const catalogued = index.resources.filter((tool) => tool.tier === "catalogued");
  const categories = [...new Set(catalogued.map((tool) => tool.category))].sort((left, right) => left.localeCompare(right, "en", { numeric: true }));
  const categoryLines = categories.map((category) => {
    const links = catalogued.filter((tool) => tool.category === category).map(cardLink);
    return `- **${category.replace(/^A\d+\.\s*/, "")}**: ${links.join(", ")}`;
  });
  return [
    "## Tool catalogue",
    "",
    "Generated by `vcr catalog build` from `catalog/tools/`; do not edit between the markers. ✓ validated, ◐ partial evidence. Agents route through [`catalog/INDEX.md`](catalog/INDEX.md); `vcr tools info <id>` prints any card.",
    "",
    `### Core (${core.length})`,
    "",
    ...core.map((tool) => `- ${cardLink(tool)} — ${tool.role}`),
    "",
    `### Catalogued (${catalogued.length})`,
    "",
    ...categoryLines,
  ].join("\n");
}

/** Replaces the marked block in README.md; the README must carry both markers, in order. */
export function spliceReadmeToc(readme: string, toc: string): Result<string> {
  const start = readme.indexOf(README_TOC_MARKERS.start);
  const end = readme.indexOf(README_TOC_MARKERS.end);
  if (start === -1 || end === -1 || end < start) {
    return fail("README_TOC_MARKERS_MISSING", `README.md needs ${README_TOC_MARKERS.start} followed by ${README_TOC_MARKERS.end}; add both where the tool catalogue should go and rerun vcr catalog build.`);
  }
  return ok(`${readme.slice(0, start + README_TOC_MARKERS.start.length)}\n${toc}\n${readme.slice(end)}`);
}

/** Writes both index files unless `checkOnly`; either way reports which committed files were stale. */
export function writeCatalogIndex(repositoryRoot: string, checkOnly: boolean): Result<BuildOutcome> {
  const built = buildCatalogIndex(repositoryRoot);
  if (!built.ok) return built;
  const outputs: Array<[string, string]> = [
    ["catalog/tools.json", serializeIndex(built.value)],
    ["catalog/INDEX.md", renderMarkdownIndex(built.value, repositoryRoot)],
    ["catalog/CANDIDATES.md", renderCandidatesIndex(built.value, repositoryRoot)],
  ];
  // Fixture repositories in tests have no README; the harness README must carry the markers.
  const readme = safeRead(join(repositoryRoot, "README.md"));
  if (readme !== null) {
    const spliced = spliceReadmeToc(readme, renderReadmeToc(built.value));
    if (!spliced.ok) return spliced;
    outputs.push(["README.md", spliced.value]);
  }
  const staleFiles: string[] = [];
  for (const [relativePath, next] of outputs) {
    const absolutePath = join(repositoryRoot, relativePath);
    if (safeRead(absolutePath) === next) continue;
    staleFiles.push(relativePath);
    if (!checkOnly) writeFileSync(absolutePath, next);
  }
  return ok({ recordCount: built.value.resources.length, wasStale: staleFiles.length > 0, staleFiles });
}

/** Size of a repository file in whole kilobytes, or null when it is missing. */
export function fileSizeKb(repositoryRoot: string, relativePath: string): number | null {
  try {
    return Math.max(1, Math.round(statSync(join(repositoryRoot, relativePath)).size / 1024));
  } catch {
    return null;
  }
}

// === PRIVATE HELPERS ===

function indexLine(tool: ToolSummary, repositoryRoot: string): string {
  const evidence = tool.validation.status === "validated" ? " ✓" : tool.validation.status === "partial" ? " ◐" : "";
  const capabilities = tool.tier === "candidate" ? "" : ` · ${tool.capabilities.join(", ")}`;
  const guide = tool.skill ? " · guide" : "";
  return `- \`${tool.id}\`${evidence} — ${tool.role}${capabilities}${guide}`;
}

function cardLink(tool: ToolSummary): string {
  const evidence = tool.validation.status === "validated" ? " ✓" : tool.validation.status === "partial" ? " ◐" : "";
  return `[${tool.name}](catalog/tools/${tool.id}.json)${evidence}`;
}

function safeRead(filePath: string): string | null {
  try {
    return readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}
