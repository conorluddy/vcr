import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { listJsonFiles, readJsonFile } from "./repository.js";
import { fail, ok, type Result } from "./result.types.js";
import type { ToolSummary } from "./tools.js";

// === TYPES ===

export interface CatalogIndex {
  schema_version: string;
  generated_from: "catalog/tools/*.json";
  resources: ToolSummary[];
}

export interface BuildOutcome {
  recordCount: number;
  /** True when a committed index file differs from what the per-tool files produce. */
  wasStale: boolean;
  staleFiles: string[];
}

const TIER_ORDER = ["core", "catalogued", "candidate"] as const;

const INDEX_HEADER = `# VCR tool index

Tier 0 of the catalogue tree, generated by \`vcr catalog build\`. One line per tool: id, one-line role, capabilities, whether validation evidence exists (✓) and whether a guide exists. Read this whole file (under 16 KB) to route a task, then descend only as far as the task needs:

- **Tier 1, the card** (about 200 tokens): \`vcr tools info <id>\` or \`catalog/tools/<id>.json\`. Summary, use when, avoid when, pairs with, install, evidence. Compare a shortlist here.
- **Tier 2, the guide** (1 to 2k tokens): \`vcr tools info <id> --full\` or \`skills/<id>/SKILL.md\`. Clock rules, recipes, gotchas. Load one at a time, once a tool is chosen.
- **Tier 3, examples** (source code): \`vcr tools examples <id>\` then \`examples/<id>/\`. Load one at a time.

Tiers: core = operational target with a skill and example; catalogued = real option with a known automation route; candidate = seen during discovery, not yet assessed. A ✓ means validation evidence exists on this machine's records; nothing here claims a tool is installed.
`;

// === PUBLIC API ===

export function buildCatalogIndex(repositoryRoot: string): Result<CatalogIndex> {
  const resources: ToolSummary[] = [];
  for (const filePath of listJsonFiles(join(repositoryRoot, "catalog/tools"))) {
    const record = readJsonFile<ToolSummary>(filePath);
    if (!record.ok) return record;
    const expectedFile = `${record.value.id}.json`;
    if (!filePath.endsWith(`/${expectedFile}`)) return fail("CATALOG_FILENAME_MISMATCH", `${filePath}: file must be named ${expectedFile} to match its id`);
    resources.push(record.value);
  }
  resources.sort((left, right) => left.id.localeCompare(right.id));
  return ok({ schema_version: "1.1.0", generated_from: "catalog/tools/*.json", resources });
}

export function serializeIndex(index: CatalogIndex): string {
  return `${JSON.stringify(index, null, 2)}\n`;
}

/** Tier 0 as Markdown: grouped by tier, one line per tool, sized to be read whole. */
export function renderMarkdownIndex(index: CatalogIndex, repositoryRoot: string): string {
  const sections = TIER_ORDER.map((tier) => {
    const tools = index.resources.filter((tool) => tool.tier === tier);
    const lines = tools.map((tool) => indexLine(tool, repositoryRoot));
    return `## ${tier} (${tools.length})\n\n${lines.join("\n")}\n`;
  });
  return `${INDEX_HEADER}\n${sections.join("\n")}`;
}

/** Writes both index files unless `checkOnly`; either way reports which committed files were stale. */
export function writeCatalogIndex(repositoryRoot: string, checkOnly: boolean): Result<BuildOutcome> {
  const built = buildCatalogIndex(repositoryRoot);
  if (!built.ok) return built;
  const outputs: Array<[string, string]> = [
    ["catalog/tools.json", serializeIndex(built.value)],
    ["catalog/INDEX.md", renderMarkdownIndex(built.value, repositoryRoot)],
  ];
  const staleFiles: string[] = [];
  for (const [relativePath, next] of outputs) {
    const absolutePath = join(repositoryRoot, relativePath);
    if (safeRead(absolutePath) === next) continue;
    staleFiles.push(relativePath);
    if (!checkOnly) writeFileSync(absolutePath, next);
  }
  return ok({ recordCount: built.value.resources.length, wasStale: staleFiles.length > 0, staleFiles });
}

/** Size of a repository file in whole kilobytes, or null when it is missing. */
export function fileSizeKb(repositoryRoot: string, relativePath: string): number | null {
  try {
    return Math.max(1, Math.round(statSync(join(repositoryRoot, relativePath)).size / 1024));
  } catch {
    return null;
  }
}

// === PRIVATE HELPERS ===

function indexLine(tool: ToolSummary, repositoryRoot: string): string {
  const evidence = tool.validation.status === "validated" || tool.validation.status === "partial" ? " ✓" : "";
  const capabilities = tool.tier === "candidate" ? "" : ` · ${tool.capabilities.join(", ")}`;
  const guide = tool.skill ? " · guide" : "";
  return `- \`${tool.id}\`${evidence} — ${tool.role}${capabilities}${guide}`;
}

function safeRead(filePath: string): string | null {
  try {
    return readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}
