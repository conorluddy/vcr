#!/usr/bin/env bash
# Generate a 120 BPM click track and a 440 Hz sine with FFmpeg, then run sonic-annotator with one onset transform and one
# pitch transform from the Vamp Plugin Pack, twice each, writing CSV and JAMS. Run ./fetch-tools.sh first.
# Predeclared checks (see README "Plan, before running") must all pass before the summary is recorded or diffed.
set -euo pipefail
cd "$(dirname "$0")"

SONIC_ANNOTATOR=output/bin/sonic-annotator
export VAMP_PATH="$PWD/output/vamp"
ONSET_TRANSFORM_ID=vamp:qm-vamp-plugins:qm-onsetdetector:onsets
PITCH_TRANSFORM_ID=vamp:vamp-aubio:aubiopitch:frequency
SAMPLE_RATE_HZ=44100
CLICK_DURATION_S=10
CLICK_FIRST_S=0.25
CLICK_PERIOD_S=0.5
CLICK_COUNT=20
CLICK_BURST_S=0.05
SINE_HZ=440
SINE_DURATION_S=4
DURATION_TOLERANCE_S=0.01
ONSET_TOLERANCE_S=0.025
MAX_ONSET_MISSES=0
MAX_ONSET_EXTRAS=0
PITCH_WINDOW_START_S=0.5
PITCH_WINDOW_END_S=3.5
PITCH_TOLERANCE_CENTS=10
MIN_PITCH_FRAMES=5
MIN_JAMS_OBSERVATIONS=20

if [[ ! -x "$SONIC_ANNOTATOR" || ! -f output/vamp/qm-vamp-plugins.dylib || ! -f output/vamp/vamp-aubio.dylib ]]; then
  echo "sonic-annotator-features: sonic-annotator or the Vamp libraries are missing under output/. Run ./fetch-tools.sh first." >&2
  exit 1
fi

rm -rf output/inputs output/transforms output/run-a output/run-b output/summary.json output/click-truth.txt output/pitch-window.txt
mkdir -p output/inputs output/transforms

# Clicks sit where (t + FIRST) is a multiple of PERIOD, so the first click lands at FIRST seconds.
since="mod(t+${CLICK_FIRST_S},${CLICK_PERIOD_S})"
ffmpeg -y -loglevel error -f lavfi -i "aevalsrc='0.8*sin(2*PI*1000*${since})*exp(-60*${since})*lt(${since},${CLICK_BURST_S})':s=${SAMPLE_RATE_HZ}:d=${CLICK_DURATION_S}" \
  -ac 1 -c:a pcm_s16le output/inputs/clicks.wav
ffmpeg -y -loglevel error -f lavfi -i "aevalsrc='0.5*sin(2*PI*${SINE_HZ}*t)':s=${SAMPLE_RATE_HZ}:d=${SINE_DURATION_S}" \
  -ac 1 -c:a pcm_s16le output/inputs/sine440.wav

# Transform definitions are generated by the tool itself and then loaded with -t, as sonic-annotator's README recommends.
$SONIC_ANNOTATOR -s "$ONSET_TRANSFORM_ID" > output/transforms/onsets.n3
$SONIC_ANNOTATOR -s "$PITCH_TRANSFORM_ID" > output/transforms/pitch.n3
$SONIC_ANNOTATOR -l > output/transform-list.txt

runPipeline() {
  local dir="$1"
  local log="$dir/sonic-annotator.log"
  mkdir -p "$dir/jams-onsets" "$dir/jams-pitch"
  $SONIC_ANNOTATOR -t output/transforms/onsets.n3 output/inputs/clicks.wav -w csv --csv-stdout --csv-omit-filename > "$dir/onsets.csv" 2>>"$log"
  $SONIC_ANNOTATOR -t output/transforms/onsets.n3 output/inputs/clicks.wav -w jams --jams-basedir "$dir/jams-onsets" 2>>"$log"
  $SONIC_ANNOTATOR -t output/transforms/pitch.n3 output/inputs/sine440.wav -w csv --csv-stdout --csv-omit-filename > "$dir/pitch.csv" 2>>"$log"
  $SONIC_ANNOTATOR -t output/transforms/pitch.n3 output/inputs/sine440.wav -w jams --jams-basedir "$dir/jams-pitch" 2>>"$log"
}

runPipeline output/run-a
runPipeline output/run-b

probeStream() { ffprobe -v error -select_streams a:0 -show_entries stream=sample_rate,channels -of csv=p=0 "$1"; }
probeDuration() { ffprobe -v error -show_entries format=duration -of csv=p=0 "$1"; }
sampleRateOf() { probeStream "$1" | cut -d, -f1; }
channelsOf() { probeStream "$1" | cut -d, -f2; }
withinAbs() { awk -v a="$1" -v b="$2" -v tol="$3" 'BEGIN { d = a - b; if (d < 0) d = -d; exit !(d <= tol) }'; }
fixed() { awk -v v="$1" -v digits="$2" 'BEGIN { printf "%." digits "f", v }'; }

clickDuration=$(probeDuration output/inputs/clicks.wav)
sineDuration=$(probeDuration output/inputs/sine440.wav)
inputsMatchSpec=false
if [[ "$(sampleRateOf output/inputs/clicks.wav)" == "$SAMPLE_RATE_HZ" && "$(channelsOf output/inputs/clicks.wav)" == "1" \
  && "$(sampleRateOf output/inputs/sine440.wav)" == "$SAMPLE_RATE_HZ" && "$(channelsOf output/inputs/sine440.wav)" == "1" ]] \
  && withinAbs "$clickDuration" "$CLICK_DURATION_S" "$DURATION_TOLERANCE_S" && withinAbs "$sineDuration" "$SINE_DURATION_S" "$DURATION_TOLERANCE_S"; then
  inputsMatchSpec=true
fi

listingHasBothIds=false
if grep -Fxq "$ONSET_TRANSFORM_ID" output/transform-list.txt && grep -Fxq "$PITCH_TRANSFORM_ID" output/transform-list.txt; then
  listingHasBothIds=true
fi

# Truth comes from the constants above, not from the generated output.
awk -v first="$CLICK_FIRST_S" -v period="$CLICK_PERIOD_S" -v count="$CLICK_COUNT" \
  'BEGIN { for (k = 0; k < count; k++) printf "%.6f\n", first + k * period }' > output/click-truth.txt

# Greedy one-to-one match: each detection pairs with its nearest unmatched true onset inside the tolerance.
# Input: the truth file, then the detections (one time per line).
matchOnsets() {
  awk -v tolerance="$ONSET_TOLERANCE_S" '
    FNR == NR { truth[++truthCount] = $1; next }
    NF { detected[++detectedCount] = $1 }
    END {
      for (i = 1; i <= detectedCount; i++) {
        best = 0; bestDistance = 1e9
        for (j = 1; j <= truthCount; j++) {
          distance = detected[i] - truth[j]; if (distance < 0) distance = -distance
          if (distance < bestDistance && !used[j]) { bestDistance = distance; best = j }
        }
        if (best > 0 && bestDistance <= tolerance) {
          used[best] = 1; matched++
          if (bestDistance * 1000 > maxErrorMs) maxErrorMs = bestDistance * 1000
        } else { extras++ }
      }
      for (j = 1; j <= truthCount; j++) if (!used[j]) misses++
      printf "%d %d %d %.3f\n", matched + 0, misses + 0, extras + 0, maxErrorMs + 0
    }' output/click-truth.txt "$1"
}

read -r onsetsMatched onsetMisses onsetExtras onsetMaxErrorMs < <(cut -d, -f1 output/run-a/onsets.csv | matchOnsets /dev/stdin)
onsetDetections=$(wc -l < output/run-a/onsets.csv | tr -d ' ')
onsetsOk=false
if (( onsetMisses <= MAX_ONSET_MISSES && onsetExtras <= MAX_ONSET_EXTRAS )) \
  && awk -v e="$onsetMaxErrorMs" -v tol="$(awk -v s="$ONSET_TOLERANCE_S" 'BEGIN { printf "%.3f", s * 1000 }')" 'BEGIN { exit !(e <= tol) }'; then
  onsetsOk=true
fi

# Pitch: voiced frames (value > 0) inside the window; the median frequency, its cents error against the sine, and the frame count.
awk -F, -v start="$PITCH_WINDOW_START_S" -v end="$PITCH_WINDOW_END_S" '$1 >= start && $1 <= end && $2 > 0 { print $2 }' output/run-a/pitch.csv \
  | sort -g > output/pitch-window.txt
pitchFrames=$(wc -l < output/pitch-window.txt | tr -d ' ')
pitchMedianHz=$(awk '{ values[NR] = $1 } END {
    if (NR == 0) { print 0; exit }
    if (NR % 2) printf "%.6f", values[(NR + 1) / 2]; else printf "%.6f", (values[NR / 2] + values[NR / 2 + 1]) / 2 }' output/pitch-window.txt)
pitchCentsError=$(awk -v measured="$pitchMedianHz" -v expected="$SINE_HZ" 'BEGIN { if (measured <= 0) print 0; else printf "%.3f", 1200 * log(measured / expected) / log(2) }')
pitchOk=false
if (( pitchFrames >= MIN_PITCH_FRAMES )) && withinAbs "$pitchCentsError" 0 "$PITCH_TOLERANCE_CENTS"; then pitchOk=true; fi

csvRowsOnsets=$(wc -l < output/run-a/onsets.csv | tr -d ' ')
csvRowsPitch=$(wc -l < output/run-a/pitch.csv | tr -d ' ')
jamsOnsetObservations=$(jq '[.annotations[].data | length] | max // 0' output/run-a/jams-onsets/clicks.json)
jamsPitchObservations=$(jq '[.annotations[].data | length] | max // 0' output/run-a/jams-pitch/sine440.json)
writersOk=false
if (( csvRowsOnsets > 0 && csvRowsPitch > 0 && jamsOnsetObservations >= MIN_JAMS_OBSERVATIONS && jamsPitchObservations > 0 )); then
  writersOk=true
fi

listedOk=$listingHasBothIds

rerunIdentical=true
for file in onsets.csv pitch.csv jams-onsets/clicks.json jams-pitch/sine440.json; do
  if ! cmp -s "output/run-a/$file" "output/run-b/$file"; then rerunIdentical=false; fi
done

jq -n -S \
  --argjson clickSampleRateHz "$(sampleRateOf output/inputs/clicks.wav)" \
  --argjson clickChannels "$(channelsOf output/inputs/clicks.wav)" \
  --argjson clickDurationS "$(fixed "$clickDuration" 3)" \
  --argjson sineSampleRateHz "$(sampleRateOf output/inputs/sine440.wav)" \
  --argjson sineChannels "$(channelsOf output/inputs/sine440.wav)" \
  --argjson sineDurationS "$(fixed "$sineDuration" 3)" \
  --argjson truthOnsets "$CLICK_COUNT" \
  --argjson onsetDetections "$onsetDetections" \
  --argjson onsetsMatched "$onsetsMatched" \
  --argjson onsetMisses "$onsetMisses" \
  --argjson onsetExtras "$onsetExtras" \
  --argjson onsetMaxErrorMs "$onsetMaxErrorMs" \
  --argjson pitchFrames "$pitchFrames" \
  --arg pitchMedianHz "$(fixed "$pitchMedianHz" 1)" \
  --arg pitchCentsError "$(fixed "$pitchCentsError" 1)" \
  --argjson jamsOnsetObservations "$jamsOnsetObservations" \
  --argjson jamsPitchObservations "$jamsPitchObservations" \
  --argjson rerunIdentical "$rerunIdentical" \
  --argjson inputsMatchSpec "$inputsMatchSpec" \
  --argjson listedOk "$listedOk" \
  --argjson onsetsOk "$onsetsOk" \
  --argjson pitchOk "$pitchOk" \
  --argjson writersOk "$writersOk" \
  '{
    inputs: {
      clicks: { sampleRateHz: $clickSampleRateHz, channels: $clickChannels, durationS: $clickDurationS },
      sine440: { sampleRateHz: $sineSampleRateHz, channels: $sineChannels, durationS: $sineDurationS }
    },
    listing: { ids_listed: $listedOk },
    onsets: { truth: $truthOnsets, detections: $onsetDetections, matched: $onsetsMatched, misses: $onsetMisses, extras: $onsetExtras, maxErrorMs: $onsetMaxErrorMs },
    pitch: { frames: $pitchFrames, medianHz: ($pitchMedianHz | tonumber), centsError: ($pitchCentsError | tonumber) },
    writers: { jams_onset_observations: $jamsOnsetObservations, jams_pitch_observations: $jamsPitchObservations },
    rerun_identical: $rerunIdentical,
    checks: {
      inputs_match_spec: $inputsMatchSpec,
      transforms_listed: $listedOk,
      onsets_within_tolerance: $onsetsOk,
      pitch_within_tolerance: $pitchOk,
      writers_non_empty: $writersOk,
      rerun_identical: $rerunIdentical
    }
  }' > output/summary.json

checksPassed=false
if jq -e '[.rerun_identical, .checks[]] | all(. == true)' output/summary.json >/dev/null; then checksPassed=true; fi

if [[ "${1:-}" == "--record" ]]; then
  mkdir -p expected
  jq -S . output/summary.json > expected/summary.json
  echo "sonic-annotator-features: recorded expected/summary.json (all predeclared checks pass: $checksPassed)"
  exit 0
fi

if [[ ! -f expected/summary.json ]]; then
  echo "sonic-annotator-features: no expected/summary.json; run with --record after checking the output." >&2
  exit 1
fi
if ! diff <(jq -S . output/summary.json) expected/summary.json; then
  echo "sonic-annotator-features: summary differs from expected/summary.json" >&2
  exit 1
fi
if [[ "$checksPassed" != "true" ]]; then
  echo "sonic-annotator-features: predeclared checks failed; see output/summary.json" >&2
  exit 1
fi
echo "sonic-annotator-features: OK"
